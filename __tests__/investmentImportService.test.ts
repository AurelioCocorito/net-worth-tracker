/**
 * The commit order of the import's trades: by date, then the replay's same-day rank (buy < sell <
 * correction), then the file's line — the ledger route validates each write against the trades
 * already stored, so a same-day sale sent before its buy would be refused.
 */
import { describe, it, expect, vi } from 'vitest';

vi.mock('@/lib/firebase/config', () => ({ db: {} }));
vi.mock('@/lib/services/assetService', () => ({ createAsset: vi.fn(), deleteAsset: vi.fn() }));
vi.mock('@/lib/services/assetTransactionService', () => ({
  createAssetTransaction: vi.fn(),
  deleteAssetTransaction: vi.fn(),
  getAssetTransactions: vi.fn(),
}));
vi.mock('@/lib/utils/authFetch', () => ({ authenticatedFetch: vi.fn() }));

import { buildImportedDividendData, commitDividendRows, orderTradeRowsForCommit } from '@/lib/services/investmentImportService';
import { authenticatedFetch } from '@/lib/utils/authFetch';
import type { PlannedDividendRow, PlannedTradeRow } from '@/types/expenseImport';

const row = (line: number, day: number, tradeType: PlannedTradeRow['tradeType']): PlannedTradeRow => ({
  line,
  date: new Date(2026, 9, day, 12),
  tradeType,
  isin: 'IE0000000001',
  quantity: 1,
  pricePerUnit: 10,
});

describe('orderTradeRowsForCommit', () => {
  it('sorts by date, then buy < sell < correction, then line', () => {
    const ordered = orderTradeRowsForCommit([
      row(1, 2, 'sell'),
      row(2, 1, 'adjustment'),
      row(3, 2, 'buy'),
      row(4, 1, 'buy'),
      row(5, 2, 'buy'),
    ]);
    expect(ordered.map((r) => r.line)).toEqual([4, 2, 3, 5, 1]);
  });
});

const dividend = (line: number, day: number, assetId?: string): PlannedDividendRow => ({
  line,
  paymentDate: new Date(2026, 9, day, 12),
  exDate: new Date(2026, 9, day - 2, 12),
  dividendType: 'ordinary',
  isin: 'IE0000000002',
  assetId,
  quantity: 200,
  grossAmount: 50,
  taxAmount: 13,
  currency: 'EUR',
});

describe('buildImportedDividendData', () => {
  it('derives the per-unit amount and the net, as a manual entry stamped with the batch', () => {
    expect(buildImportedDividendData(dividend(1, 15), 'a-1', 'batch-1')).toMatchObject({
      assetId: 'a-1', dividendPerShare: 0.25, quantity: 200, grossAmount: 50, taxAmount: 13, netAmount: 37,
      dividendType: 'ordinary', isAutoGenerated: false, importBatchId: 'batch-1',
    });
  });
});

describe('commitDividendRows', () => {
  it('posts oldest first, resolves a created instrument by ISIN, and stops at the first refusal', async () => {
    const fetchMock = vi.mocked(authenticatedFetch);
    fetchMock.mockReset();
    fetchMock
      .mockResolvedValueOnce({ ok: true, json: async () => ({}) } as Response)
      .mockResolvedValueOnce({ ok: false, json: async () => ({ error: 'rifiutato' }) } as Response);
    const result = await commitDividendRows('u1', [dividend(3, 20), dividend(2, 10), dividend(4, 25)], new Map([['IE0000000002', 'new-1']]), 'b');
    expect(result).toEqual({ created: 1, failure: { line: 3, message: 'rifiutato' } });
    expect(fetchMock).toHaveBeenCalledTimes(2);
    const first = JSON.parse((fetchMock.mock.calls[0][1] as RequestInit).body as string);
    expect(first.dividendData).toMatchObject({ assetId: 'new-1', importBatchId: 'b' });
  });
});
