/**
 * Impostazioni › Spese · Import CSV — dividend rows (2026-10-25). Desktop 1440.
 *
 * What only the browser against the emulators can prove: a CSV «dividendo» row becomes a payment
 * of the Dividendi registry through POST /api/dividends — gross, withholding, net, per-unit amount,
 * stamped with the batch — with its income row in Tracciamento when an income category for
 * dividends is set; a payment the registry already holds for that day is discarded in the preview;
 * «Annulla import» deletes the payment AND its income row. Every outcome is asserted on Firestore
 * (Admin SDK). The parsing rules live in __tests__/expenseImport.test.ts.
 *
 * The test plants its own instrument, category and earlier payment (decoy names absent from the
 * seed), sets the dividend income category on the settings document and puts back what was there
 * in `finally` — data-only, never a re-seed (doc/guide/e2e-emulatori.md § Browser-Driven E2E).
 */

import { test, expect } from '@playwright/test';

process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8080';
process.env.GCLOUD_PROJECT = 'demo-net-worth';

const UID = 'test-user-1';
const ETF_ID = 'e2e-importdiv-lontra';
const CATEGORY_ID = 'e2e-importdiv-cedole-lontra';
const EARLIER_ID = 'e2e-importdiv-earlier';
const ETF_ISIN = 'IE00LONTRA01';

test.setTimeout(240_000);

async function admin() {
  const { initializeApp, getApps } = await import('firebase-admin/app');
  const { getFirestore } = await import('firebase-admin/firestore');
  const app = getApps()[0] ?? initializeApp({ projectId: process.env.GCLOUD_PROJECT });
  return getFirestore(app);
}

async function plant(db: FirebaseFirestore.Firestore) {
  const now = new Date();
  await db.collection('assets').doc(ETF_ID).set({
    userId: UID, ticker: 'LONTRA', name: 'Lontra Dividend ETF', type: 'etf', assetClass: 'equity', currency: 'EUR',
    quantity: 200, averageCost: 50, averageCostEur: 50, currentPrice: 55, isLiquid: true, autoUpdatePrice: false,
    taxRate: 26, isin: ETF_ISIN, createdAt: now, updatedAt: now, lastPriceUpdate: now,
  });
  await db.collection('expenseCategories').doc(CATEGORY_ID).set({
    userId: UID, name: 'Cedole Lontra', type: 'income', subCategories: [], createdAt: now, updatedAt: now,
  });
  // A payment already in the registry (as the Borsa Italiana scrape would write it): 2026-09-15.
  await db.collection('dividends').doc(EARLIER_ID).set({
    userId: UID, assetId: ETF_ID, assetTicker: 'LONTRA', assetName: 'Lontra Dividend ETF', assetIsin: ETF_ISIN,
    exDate: new Date(2026, 8, 10, 12), paymentDate: new Date(2026, 8, 15, 12), dividendPerShare: 0.2, quantity: 200,
    grossAmount: 40, taxAmount: 10.4, netAmount: 29.6, currency: 'EUR', dividendType: 'ordinary', isAutoGenerated: true,
    createdAt: now, updatedAt: now,
  });
}

async function remove(db: FirebaseFirestore.Firestore) {
  const dividends = await db.collection('dividends').where('userId', '==', UID).where('assetId', '==', ETF_ID).get();
  for (const d of dividends.docs) await d.ref.delete();
  const incomes = await db.collection('expenses').where('userId', '==', UID).where('categoryId', '==', CATEGORY_ID).get();
  for (const e of incomes.docs) await e.ref.delete();
  await db.collection('expenseCategories').doc(CATEGORY_ID).delete();
  await db.collection('assets').doc(ETF_ID).delete();
}

const CSV = [
  'data;importo;tipo;isin;quantita;tasse;data_stacco;note',
  `2026-10-15;50,00;dividendo;${ETF_ISIN};200;13,00;2026-10-08;trimestrale`,
  `2026-09-15;40,00;dividendo;${ETF_ISIN};200;10,40;2026-09-10;`,
].join('\n');

test('dividend rows of the CSV import land in Dividendi with their income row, and «Annulla import» removes both', async ({ page }) => {
  const db = await admin();
  await remove(db);
  const settingsRef = db.collection('assetAllocationTargets').doc(UID);
  const settingsBefore = (await settingsRef.get()).data();
  await plant(db);
  await settingsRef.set({ dividendIncomeCategoryId: CATEGORY_ID }, { merge: true });

  try {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('/dashboard/settings?tab=spese', { waitUntil: 'load' });
    const input = page.getByLabel('Carica file CSV storico spese');
    await expect(input).toBeAttached({ timeout: 90_000 });
    await input.setInputFiles({ name: 'dividendi.csv', mimeType: 'text/csv', buffer: Buffer.from(CSV, 'utf-8') });

    // The preview counts the new payment and discards the one already in the registry.
    await expect(page.getByText(/1 dividendo \(37\s€ netti\)/)).toBeVisible({ timeout: 30_000 });
    await page.getByRole('button', { name: 'Mostra 1 righe scartate' }).click();
    await expect(page.getByText(/già registrato in Dividendi/)).toBeVisible();

    await page.getByRole('button', { name: 'Importa 1 voci' }).click();
    const tile = page.getByLabel('Import CSV');
    await expect(tile.getByText('Importate 1 transazioni.')).toBeVisible({ timeout: 90_000 });

    const imported = (
      await db.collection('dividends').where('userId', '==', UID).where('assetId', '==', ETF_ID).where('isAutoGenerated', '==', false).get()
    ).docs;
    expect(imported).toHaveLength(1);
    const payment = imported[0].data();
    expect(payment).toMatchObject({ grossAmount: 50, taxAmount: 13, netAmount: 37, dividendPerShare: 0.25, quantity: 200, notes: 'trimestrale' });
    expect(typeof payment.importBatchId).toBe('string');
    const incomes = await db.collection('expenses').where('userId', '==', UID).where('categoryId', '==', CATEGORY_ID).get();
    expect(incomes.size).toBe(1);
    expect(incomes.docs[0].data().amount).toBe(37);

    // «Annulla import»: the payment and its income row are gone, the earlier payment stays.
    await tile.getByRole('button', { name: 'Annulla import' }).click();
    await expect(page.getByText(/Import annullato/).first()).toBeVisible({ timeout: 90_000 });
    await expect(tile.getByRole('button', { name: 'Carica file CSV' })).toBeVisible({ timeout: 90_000 });
    expect((await db.collection('dividends').doc(imported[0].id).get()).exists).toBe(false);
    expect((await db.collection('expenses').where('userId', '==', UID).where('categoryId', '==', CATEGORY_ID).get()).size).toBe(0);
    expect((await db.collection('dividends').doc(EARLIER_ID).get()).exists).toBe(true);
  } finally {
    await remove(db);
    const { FieldValue } = await import('firebase-admin/firestore');
    await settingsRef.set(
      { dividendIncomeCategoryId: settingsBefore?.dividendIncomeCategoryId ?? FieldValue.delete() },
      { merge: true }
    );
  }
});
